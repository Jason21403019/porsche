// 根據實際圖片結構生成正確的圖片路徑
const generateActualImagePath = (
  carModel,
  colorIndex,
  wheelIndex,
  packageSuffix
) => {
  const modelPath = carModelToPath[carModel]
  if (!modelPath) return null

  const availableColors = carColors[carModel] || []
  if (colorIndex >= availableColors.length) return null

  const colorInfo = availableColors[colorIndex]
  const wheelNumber = String(wheelIndex + 1).padStart(2, '0')

  // 根據不同輪圈的命名模式生成路徑
  if (wheelIndex === 0) {
    // wheel01 使用 01-02.png, 01-03.png, 01-04.png 格式
    return `${colorInfo.path}/wheel${wheelNumber}/${wheelNumber}-${packageSuffix}.png`
  } else if (wheelIndex === 1) {
    // wheel02 使用 02-1.png, 02-2.png, 02-3.png 格式
    const suffixMap = { '02': '1', '03': '2', '04': '3' }
    const suffix = suffixMap[packageSuffix] || '1'
    return `${colorInfo.path}/wheel${wheelNumber}/${wheelNumber}-${suffix}.png`
  } else if (wheelIndex === 2) {
    // wheel03 使用 03-1.png, 03-2.png, 03-3.png 格式
    const suffixMap = { '02': '1', '03': '2', '04': '3' }
    const suffix = suffixMap[packageSuffix] || '1'
    return `${colorInfo.path}/wheel${wheelNumber}/${wheelNumber}-${suffix}.png`
  }

  return null
}

