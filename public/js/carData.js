// 獲取輪圈圖片路徑 - 使用 JSON 檔案中的實際路徑
export const getWheelImagePath = (carModel, colorCode, wheelNumber) => {
  const modelData = jsonDataMap[carModel]
  if (!modelData) {
    return `/img/wheel${wheelNumber}.png`
  }
  // 使用輔助函數查找顏色鍵值
  const colorKey = findColorKey(modelData, colorCode)

  if (!colorKey || !modelData[colorKey]) {
    return `/img/wheel${wheelNumber}.png`
  }
  const colorData = modelData[colorKey]

  // 檢查是否需要特殊處理
  const specialResult = getWheelImagePathSpecial(
    carModel,
    colorData,
    wheelNumber
  )
  if (specialResult !== null) {
    return specialResult
  }

  const wheelKey = `wheel${String(wheelNumber).padStart(2, '0')}`

  // 檢查輪圈資料夾是否存在
  if (colorData[wheelKey]) {
    // 嘗試多種檔案名稱格式
    const possibleFileNames = [
      `${String(wheelNumber).padStart(2, '0')}.png`,
      `0${wheelNumber}.png`,
      `${wheelNumber}.png`,
      `wheel${wheelNumber}.png`,
      `01.png`, // 預設檔案名
      `02.png`,
      `03.png`,
      `00.png`,
    ]

    for (const fileName of possibleFileNames) {
      if (colorData[wheelKey][fileName]) {
        return colorData[wheelKey][fileName]
      }
    }

    // 如果沒有找到特定的檔案，檢查是否有任何 .png 檔案
    const pngFiles = Object.keys(colorData[wheelKey]).filter(
      (key) => key.endsWith('.png') && !key.includes('Optional')
    )
    if (pngFiles.length > 0) {
      return colorData[wheelKey][pngFiles[0]]
    }
  }

  return `/img/wheel${wheelNumber}.png`
}

// 獲取選配套件圖片路徑 - 使用 JSON 檔案中的實際路徑
// 智能套件圖片路徑函數 - 支援跨車型回退
export const getSmartPackageImagePath = (
  preferredCarModel,
  fallbackCarModel,
  colorCode,
  wheelNumber,
  packageIndex
) => {
  // 首先嘗試在首選車型中查找
  const preferredResult = getOptionalPackageImagePath(
    preferredCarModel,
    colorCode,
    wheelNumber,
    packageIndex
  )
  if (preferredResult !== '/img/car1.png') {
    return preferredResult
  }

  // 如果首選車型中找不到，嘗試回退車型
  if (fallbackCarModel && fallbackCarModel !== preferredCarModel) {
    const fallbackResult = getOptionalPackageImagePath(
      fallbackCarModel,
      colorCode,
      wheelNumber,
      packageIndex
    )
    if (fallbackResult !== '/img/car1.png') {
      return fallbackResult
    }
  }

  // 如果都找不到，嘗試在回退車型中使用第一個可用顏色
  if (fallbackCarModel && fallbackCarModel !== preferredCarModel) {
    const fallbackModelData = jsonDataMap[fallbackCarModel]
    if (fallbackModelData) {
      const availableColors = Object.keys(fallbackModelData)
        .filter((key) => key.includes('color'))
        .map((key) => {
          const match = key.match(/color-?([A-F0-9]+)/i)
          return match ? match[1] : null
        })
        .filter(Boolean)

      if (availableColors.length > 0) {
        const firstColorResult = getOptionalPackageImagePath(
          fallbackCarModel,
          availableColors[0],
          wheelNumber,
          packageIndex
        )
        if (firstColorResult !== '/img/car1.png') {
          return firstColorResult
        }
      }
    }
  }

  return '/img/car1.png'
}

export const getOptionalPackageImagePath = (
  carModel,
  colorCode,
  wheelNumber,
  packageIndex
) => {
  const modelData = jsonDataMap[carModel]
  if (!modelData) {
    return `/img/car1.png`
  }

  // 使用輔助函數查找顏色鍵值
  const colorKey = findColorKey(modelData, colorCode)

  if (!colorKey || !modelData[colorKey]) {
    return `/img/car1.png`
  }
  const colorData = modelData[colorKey]

  // 檢查是否需要特殊處理
  const specialResult = getOptionalPackageImagePathSpecial(
    carModel,
    colorData,
    wheelNumber,
    packageIndex
  )
  if (specialResult !== null) {
    return specialResult
  }

  const wheelKey = `wheel${String(wheelNumber).padStart(2, '0')}`

  if (colorData[wheelKey] && colorData[wheelKey].Optional) {
    const optionalImages = colorData[wheelKey].Optional
    const imageKeys = Object.keys(optionalImages)

    // 根據 packageIndex 選擇對應的選配圖片
    if (imageKeys[packageIndex]) {
      const selectedPath = optionalImages[imageKeys[packageIndex]]
      return selectedPath
    }

    // 如果指定的 index 不存在，返回第一個可用的選配圖片
    if (imageKeys.length > 0) {
      const fallbackPath = optionalImages[imageKeys[0]]
      return fallbackPath
    }
  }

  return `/img/car1.png`
}

