// 特殊處理函數：處理不規則選配套件結構
const getOptionalPackageImagePathSpecial = (
  carModel,
  colorData,
  wheelNumber,
  packageIndex
) => {
  // 針對 Taycan Turbo S B70606 顏色的特殊處理
  if (
    carModel === 'Taycan Turbo S' &&
    colorData['00.png'] &&
    colorData.Optional
  ) {
    const optionalImages = colorData.Optional
    const imageKeys = Object.keys(optionalImages)
    if (imageKeys[packageIndex]) {
      return optionalImages[imageKeys[packageIndex]]
    }
    if (imageKeys.length > 0) {
      return optionalImages[imageKeys[0]]
    }
  }

  // 針對 Taycan Turbo GT with WP 的特殊處理
  if (carModel === 'Taycan Turbo GT with WP') {
    // 檢查色號結構
    if (colorData['00.png'] && colorData.Optional) {
      // 色號 1: 有主圖片和 Optional 資料夾
      const optionalImages = colorData.Optional
      const imageKeys = Object.keys(optionalImages)
      if (imageKeys[packageIndex]) {
        return optionalImages[imageKeys[packageIndex]]
      }
      if (imageKeys.length > 0) {
        return optionalImages[imageKeys[0]]
      }
    } else {
      // 色號 2 和 3: 直接的圖片就是選配套件
      const imageKeys = Object.keys(colorData).filter((key) =>
        key.endsWith('.png')
      )
      if (imageKeys[packageIndex]) {
        return colorData[imageKeys[packageIndex]]
      }
      if (imageKeys.length > 0) {
        return colorData[imageKeys[0]]
      }
    }
  }

  return null // 無特殊處理
}

